/**
 * Generates TOOLS.md from the tools the server actually registers (single source of truth),
 * including the minimum access level of each tool. Run with: npm run docs:tools
 */

import { writeFileSync } from 'node:fs';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import type { Tool } from '@modelcontextprotocol/sdk/types.js';
import { ACCESS_LEVELS, type AccessLevel, normalizeConnection } from '../src/config.js';
import { createAppServer } from '../src/index.js';

const GROUPS: Array<[string, string[]]> = [
  ['Profile & diagnostics', ['hello', 'get_instance_info', 'get_my_profile', 'update_my_profile']],
  ['Bookings', [
    'list_bookings', 'get_booking', 'get_booking_summary', 'create_booking', 'reschedule_booking', 'cancel_booking',
    'confirm_booking', 'decline_booking', 'mark_no_show', 'add_booking_guests', 'remove_booking_attendee', 'update_booking_location',
  ]],
  ['Availability & calendars', ['get_available_slots', 'list_calendars', 'get_busy_times', 'list_calendar_events']],
  ['Event types & private links', [
    'list_event_types', 'get_event_type', 'create_event_type', 'update_event_type', 'delete_event_type',
    'list_private_links', 'create_private_link', 'delete_private_link',
  ]],
  ['Availability schedules', ['list_schedules', 'get_schedule', 'create_schedule', 'update_schedule', 'delete_schedule']],
  ['Video apps & webhooks', ['list_conferencing_apps', 'set_default_conferencing_app', 'list_webhooks', 'create_webhook', 'update_webhook', 'delete_webhook']],
];

async function toolsFor(access: AccessLevel): Promise<Tool[]> {
  const server = createAppServer(normalizeConnection({ apiKey: 'cal_docs', apiUrl: 'https://cal.example.com', access }), { transport: 'stdio', authMode: 'docs' });
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  await server.connect(serverTransport);
  const client = new Client({ name: 'docs', version: '1.0.0' });
  await client.connect(clientTransport);
  const { tools } = await client.listTools();
  await client.close();
  await server.close();
  return tools;
}

type Schema = {
  type?: string | string[];
  enum?: unknown[];
  const?: unknown;
  items?: Schema;
  anyOf?: Schema[];
  oneOf?: Schema[];
  properties?: Record<string, Schema>;
  required?: string[];
  description?: string;
  default?: unknown;
};

function typeOf(schema: Schema): string {
  if (schema.enum) return schema.enum.map(value => `\`${value}\``).join(' \\| ');
  if (schema.const !== undefined) return `\`${schema.const}\``;
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return union.map(typeOf).join(' \\| ');
  if (schema.type === 'array') return `${schema.items ? typeOf(schema.items) : 'unknown'}[]`;
  if (schema.type === 'object' && schema.properties) {
    return `{ ${Object.keys(schema.properties).join(', ')} }`;
  }
  return Array.isArray(schema.type) ? schema.type.join(' \\| ') : schema.type ?? 'unknown';
}

function paramRows(tool: Tool): string[] {
  const schema = tool.inputSchema as Schema;
  const required = new Set(schema.required ?? []);
  return Object.entries(schema.properties ?? {}).map(([name, property]) => {
    const description = (property.description ?? property.items?.description ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
    return `| \`${name}\` | ${typeOf(property)} | ${required.has(name) ? 'Yes' : 'No'} | ${description} |`;
  });
}

function behaviour(tool: Tool): string {
  if (tool.annotations?.destructiveHint) return 'destructive — needs `confirm: true`';
  if (tool.annotations?.readOnlyHint) return 'read-only';
  return tool.annotations?.idempotentHint ? 'changes data (safe to repeat)' : 'changes data';
}

const byLevel = new Map<AccessLevel, Tool[]>();
for (const level of ACCESS_LEVELS) byLevel.set(level, await toolsFor(level));
const all = byLevel.get('full')!;
const minimumLevel = (name: string) => ACCESS_LEVELS.find(level => byLevel.get(level)!.some(tool => tool.name === name))!;

const grouped = new Set(GROUPS.flatMap(([, names]) => names));
const missing = all.filter(tool => !grouped.has(tool.name)).map(tool => tool.name);
const stale = [...grouped].filter(name => !all.some(tool => tool.name === name));
if (missing.length || stale.length) {
  throw new Error(`Update GROUPS in scripts/generate-tools-md.ts — missing: ${missing.join(', ') || 'none'}; unknown: ${stale.join(', ') || 'none'}`);
}

const count = (level: AccessLevel) => byLevel.get(level)!.length;
const lines: string[] = [
  '# Cal.com MCP Server: tools',
  '',
  '<!-- Generated by scripts/generate-tools-md.ts from the registered tools. Do not edit by hand; run `npm run docs:tools`. -->',
  '',
  `${all.length} tools. The connection's access level decides which ones a client sees:`,
  '',
  '| Access level | Tools | What it adds |',
  '|---|---|---|',
  `| \`read\` (default) | ${count('read')} | Everything read-only: profile, bookings, availability, calendars, event types, schedules, video apps, webhooks |`,
  `| \`bookings\` | ${count('bookings')} | Booking actions (create, reschedule, cancel, confirm, decline, no-show, guests, location) and private links |`,
  `| \`full\` | ${count('full')} | Configuration: event types, schedules, profile, default video app, webhooks |`,
  '',
  'Destructive tools refuse to run until the model passes `confirm: true`, which it should only do after you agree. ' +
  'Times are read and shown in your Cal profile time zone unless a tool gets `time_zone`. ' +
  'Tools that return data accept `format`: `markdown` (default) or `json`.',
  '',
  '## Contents',
  '',
  ...GROUPS.map(([group, names]) => `- **${group}**: ${names.map(name => `[\`${name}\`](#${name})`).join(', ')}`),
  '',
];

for (const [group, names] of GROUPS) {
  lines.push('---', '', `## ${group}`, '');
  for (const name of names) {
    const tool = all.find(candidate => candidate.name === name)!;
    lines.push(`### \`${tool.name}\``, '', `**${tool.title ?? tool.name}** · access \`${minimumLevel(tool.name)}\` · ${behaviour(tool)}`, '', tool.description ?? '', '');
    const rows = paramRows(tool);
    lines.push(...(rows.length ? ['| Parameter | Type | Required | Description |', '|---|---|---|---|', ...rows, ''] : ['_No parameters._', '']));
  }
}

writeFileSync('TOOLS.md', lines.join('\n'));
console.log(`Wrote TOOLS.md (${all.length} tools)`);
